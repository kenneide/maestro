import {readFileSync, writeFileSync} from 'node:fs';
import {deflateSync} from 'node:zlib';
const root=new URL('./',import.meta.url);
const tokens=JSON.parse(readFileSync(new URL('tokens.json',root),'utf8'));
const keys=Object.keys(tokens.themes.dark);
for(const theme of Object.values(tokens.themes)) {
 if(Object.keys(theme).join()!==keys.join())throw Error('Theme keys must match');
 for(const value of Object.values(theme))if(!/^#[0-9a-f]{6}([0-9a-f]{2})?$/i.test(value))throw Error(`Invalid color ${value}`);
}
const kebab=s=>s.replace(/[A-Z]/g,c=>'-'+c.toLowerCase());
let css='/* Generated by design/generate.mjs. Edit tokens.json instead. */\n';
for(const [name,theme] of Object.entries(tokens.themes))css+=`${name==='dark'?':root, ':''}:root[data-theme="${name}"]{color-scheme:${name};${Object.entries(theme).map(([k,v])=>`--${kebab(k)}:${v};`).join('')}}\n`;
css+=':root{'+Object.entries(tokens).filter(([k])=>k!=='themes').flatMap(([group,values])=>Object.entries(values).map(([k,v])=>`--${group}-${k}:${v}px;`)).join('')+'}\n';
let cpp='// Generated by design/generate.mjs. Edit tokens.json instead.\n#pragma once\n#include <juce_graphics/juce_graphics.h>\nnamespace MaestroDesign {\nstruct Palette {\n'+keys.map(k=>`    juce::Colour ${k};`).join('\n')+'\n};\n';
for(const [name,theme] of Object.entries(tokens.themes))cpp+=`inline const Palette ${name} { ${Object.values(theme).map(v=>`juce::Colour { 0x${v.length===9?v.slice(7)+v.slice(1,7):'ff'+v.slice(1)} }`).join(', ')} };\n`;
for(const group of ['space','radius','type'])for(const [k,v]of Object.entries(tokens[group]))cpp+=`inline constexpr int ${group}_${k} = ${v};\n`;
cpp+='}\n';
// Home-screen icons: mark.svg (straight-line path only) in accent on the dark background,
// rasterised here so no image tooling is needed. iOS rounds the corners itself.
function markPolygons(){
 const d=readFileSync(new URL('mark.svg',root),'utf8').match(/ d="([^"]+)"/)[1],tokens=d.match(/[a-zA-Z]|-?\d*\.?\d+/g),polys=[];let x=0,y=0,poly=[],cmd='';
 for(let i=0;i<tokens.length;){
  if(/[a-zA-Z]/.test(tokens[i]))cmd=tokens[i++];
  const n=()=>Number(tokens[i++]),rel=cmd===cmd.toLowerCase();
  switch(cmd.toLowerCase()){
   case 'm':if(poly.length)polys.push(poly);x=(rel?x:0)+n();y=(rel?y:0)+n();poly=[[x,y]];cmd=rel?'l':'L';break;
   case 'l':x=(rel?x:0)+n();y=(rel?y:0)+n();poly.push([x,y]);break;
   case 'h':x=(rel?x:0)+n();poly.push([x,y]);break;
   case 'v':y=(rel?y:0)+n();poly.push([x,y]);break;
   case 'z':polys.push(poly);poly=[];break;
   default:throw Error(`Unsupported path command ${cmd} in mark.svg`);
  }
 }
 if(poly.length)polys.push(poly);
 return polys;
}
function png(size,polys,viewBox,fg,bg){
 const rgb=h=>h.slice(1,7).match(/../g).map(v=>parseInt(v,16)),[F,B]=[rgb(fg),rgb(bg)],scale=size*.62/viewBox,offset=(size-viewBox*scale)/2,ss=4;
 const inside=(px,py)=>{let c=false;for(const p of polys)for(let i=0,j=p.length-1;i<p.length;j=i++){const [xi,yi]=p[i],[xj,yj]=p[j];if((yi>py)!==(yj>py)&&px<(xj-xi)*(py-yi)/(yj-yi)+xi)c=!c;}return c;};
 const raw=Buffer.alloc(size*(size*3+1));
 for(let y=0;y<size;y++){
  raw[y*(size*3+1)]=0;
  for(let x=0;x<size;x++){
   let hits=0;for(let sy=0;sy<ss;sy++)for(let sx=0;sx<ss;sx++)if(inside((x+(sx+.5)/ss-offset)/scale,(y+(sy+.5)/ss-offset)/scale))hits++;
   const a=hits/(ss*ss);for(let c=0;c<3;c++)raw[y*(size*3+1)+1+x*3+c]=Math.round(F[c]*a+B[c]*(1-a));
  }
 }
 const crcTable=Array.from({length:256},(_,n)=>{for(let k=0;k<8;k++)n=n&1?0xedb88320^(n>>>1):n>>>1;return n>>>0;});
 const crc=buf=>{let c=0xffffffff;for(const b of buf)c=crcTable[(c^b)&255]^(c>>>8);return (c^0xffffffff)>>>0;};
 const chunk=(type,data)=>{const len=Buffer.alloc(4),body=Buffer.concat([Buffer.from(type),data]),sum=Buffer.alloc(4);len.writeUInt32BE(data.length);sum.writeUInt32BE(crc(body));return Buffer.concat([len,body,sum]);};
 const header=Buffer.alloc(13);header.writeUInt32BE(size,0);header.writeUInt32BE(size,4);header[8]=8;header[9]=2;
 return Buffer.concat([Buffer.from([137,80,78,71,13,10,26,10]),chunk('IHDR',header),chunk('IDAT',deflateSync(raw,{level:9})),chunk('IEND',Buffer.alloc(0))]);
}
const viewBox=Number(readFileSync(new URL('mark.svg',root),'utf8').match(/viewBox="0 0 (\d+)/)[1]),polys=markPolygons();
const icons=[180,512].map(size=>[`generated/icon-${size}.png`,png(size,polys,viewBox,tokens.themes.dark.accent,tokens.themes.dark.bg)]);
for(const [file,data]of [['generated/tokens.css',css],['generated/Tokens.h',cpp],...icons]) {
 const url=new URL(file,root);
 if(process.argv.includes('--check')){if(!Buffer.from(data).equals(readFileSync(url)))throw Error(`Design assets out of date: ${file}. Run node design/generate.mjs`);}
 else writeFileSync(url,data);
}

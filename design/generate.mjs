import {readFileSync, writeFileSync} from 'node:fs';
const root=new URL('./',import.meta.url);
const tokens=JSON.parse(readFileSync(new URL('tokens.json',root),'utf8'));
const keys=Object.keys(tokens.themes.dark);
for(const theme of Object.values(tokens.themes)) {
 if(Object.keys(theme).join()!==keys.join())throw Error('Theme keys must match');
 for(const value of Object.values(theme))if(!/^#[0-9a-f]{6}([0-9a-f]{2})?$/i.test(value))throw Error(`Invalid color ${value}`);
}
const kebab=s=>s.replace(/[A-Z]/g,c=>'-'+c.toLowerCase());
let css='/* Generated by design/generate.mjs. Edit tokens.json instead. */\n';
for(const [name,theme] of Object.entries(tokens.themes))css+=`${name==='dark'?':root, ':''}:root[data-theme="${name}"]{color-scheme:${name};${Object.entries(theme).map(([k,v])=>`--${kebab(k)}:${v};`).join('')}}\n`;
css+=':root{'+Object.entries(tokens).filter(([k])=>k!=='themes').flatMap(([group,values])=>Object.entries(values).map(([k,v])=>`--${group}-${k}:${v}px;`)).join('')+'}\n';
let cpp='// Generated by design/generate.mjs. Edit tokens.json instead.\n#pragma once\n#include <juce_graphics/juce_graphics.h>\nnamespace MaestroDesign {\nstruct Palette {\n'+keys.map(k=>`    juce::Colour ${k};`).join('\n')+'\n};\n';
for(const [name,theme] of Object.entries(tokens.themes))cpp+=`inline const Palette ${name} { ${Object.values(theme).map(v=>`juce::Colour { 0x${v.length===9?v.slice(7)+v.slice(1,7):'ff'+v.slice(1)} }`).join(', ')} };\n`;
for(const group of ['space','radius','type'])for(const [k,v]of Object.entries(tokens[group]))cpp+=`inline constexpr int ${group}_${k} = ${v};\n`;
cpp+='}\n';
for(const [file,data]of [['generated/tokens.css',css],['generated/Tokens.h',cpp]]) {
 const url=new URL(file,root);
 if(process.argv.includes('--check')){if(readFileSync(url,'utf8')!==data)throw Error(`Design assets out of date: ${file}. Run node design/generate.mjs`);}
 else writeFileSync(url,data);
}
